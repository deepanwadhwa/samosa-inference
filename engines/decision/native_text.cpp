NativeText::~NativeText() { sm_tokenizer_free(tokenizer_); }
bool NativeText::render_state(const std::string& json, std::string* output, std::string* error) {
  if(!output) return fail(error,"invalid_decision_output");
  SmTokenizerOutput text={};
  const int status=sm_decision_state(reinterpret_cast<const uint8_t*>(json.data()),json.size(),&text);
  if(status) return fail(error,status==SM_TOKENIZER_CONTEXT_LIMIT?"decision_state_limit":"invalid_decision_state");
  struct Release {SmTokenizerOutput* value;~Release(){sm_tokenizer_output_free(value);}} release{&text};
  std::string result(reinterpret_cast<const char*>(text.data),text.length);
  *output=std::move(result);return true;
}
bool NativeText::load(const std::string& model, const std::string& tokenizer, std::string* error) {
  void* replacement=nullptr;
  if(sm_tokenizer_load(reinterpret_cast<const uint8_t*>(tokenizer.data()),tokenizer.size(),&replacement))
    return fail(error,"invalid_decision_tokenizer");
  if(!model_.load(model,error)) { sm_tokenizer_free(replacement);return false; }
  sm_tokenizer_free(tokenizer_);tokenizer_=replacement;return true;
}
bool NativeText::infer(const std::vector<TextPair>& pairs, PairTruncation truncation,
                       std::vector<std::array<float,2>>* output, std::string* error,
                       EncodedPairs* observed) {
  if(!output||!tokenizer_||pairs.empty()||pairs.size()>8)
    return fail(error,"invalid_decision_input");
  std::string request="{\"texts\":[";
  size_t total=0;
  for(size_t i=0;i<pairs.size();++i) {
    const auto& pair=pairs[i];
    if(pair.premise.size()>65536||pair.hypothesis.size()>65536)
      return fail(error,"decision_input_limit");
    total+=pair.premise.size()+pair.hypothesis.size();
    if(total>524288) return fail(error,"decision_input_limit");
    if(i) request+=',';
    request+='[';quote(pair.premise,&request);request+=',';quote(pair.hypothesis,&request);request+=']';
  }
  request+="],\"max_length\":512,\"padding\":\"longest\",\"truncation\":\"";
  request+=truncation==PairTruncation::OnlyFirst?"only_first":"longest_first";
  request+="\"}";
  SmTokenizerOutput encoded={};
  const int status=sm_tokenizer_encode(tokenizer_,reinterpret_cast<const uint8_t*>(request.data()),request.size(),&encoded);
  if(status) return fail(error,status==SM_TOKENIZER_CONTEXT_LIMIT?"context_limit":"decision_tokenization_failed");
  struct Release {SmTokenizerOutput* value;~Release(){sm_tokenizer_output_free(value);}} release{&encoded};
  // Only canonical JSON generated by the linked, pinned Rust implementation
  // reaches this internal parser; public request JSON never enters this path.
  const std::string bytes(reinterpret_cast<const char*>(encoded.data),encoded.length);
  char* arena=nullptr;jval* parsed=json_parse(bytes.c_str(),&arena);
  struct Cleanup {jval* value;char* arena;~Cleanup(){json_free(value);free(arena);}} cleanup{parsed,arena};
  EncodedPairs tensors;tensors.rows=pairs.size();
  if(!matrix(json_get(parsed,"input_ids"),pairs.size(),&tensors.columns,128099,&tensors.ids)||
     !matrix(json_get(parsed,"attention_mask"),pairs.size(),&tensors.columns,1,&tensors.mask)||
     !matrix(json_get(parsed,"token_type_ids"),pairs.size(),&tensors.columns,1,&tensors.types))
    return fail(error,"invalid_decision_tokens");
  std::vector<float> raw;
  if(!model_.infer(tensors.ids,tensors.mask,tensors.rows,tensors.columns,&raw,error)) return false;
  std::vector<std::array<float,2>> result;
  for(size_t i=0;i<pairs.size();++i) result.push_back({raw[2*i],raw[2*i+1]});
  if(observed) *observed=std::move(tensors);
  *output=std::move(result);return true;
}
